# Multi-extension FITS planning
# ---------------------------------------------------------------------------


@dataclass
class MEFPlan:
    """Plan for processing every image-like extension of a MEF file.

    ``extension_indices`` is the list of extensions to process;
    ``extension_names`` is the parallel list of human-readable names
    for output directory naming.  The plan is generated by
    ``plan_mef_extensions`` based on the configured behaviour.
    """

    extension_indices: list[int]
    extension_names: list[str]


def plan_mef_extensions(
    hdulist,
    process_all: bool = False,
    requested_extension: int = 0,
) -> MEFPlan:
    """Builds a ``MEFPlan`` for the supplied HDUList.

    When ``process_all`` is True, every image-like HDU is included.
    Otherwise only the requested extension is included.
    """
    indices: list[int] = []
    names: list[str] = []
    for i, hdu in enumerate(hdulist):
        data = getattr(hdu, "data", None)
        is_image = data is not None and hasattr(data, "shape") and data.ndim >= 2
        if not is_image:
            continue
        if not process_all and i != requested_extension:
            continue
        indices.append(i)
        ext_name = getattr(hdu, "name", None) or f"ext{i}"
        names.append(str(ext_name))
    if not indices:
        # Always include the requested extension as a fallback
        indices = [requested_extension]
        names = [f"ext{requested_extension}"]
    return MEFPlan(extension_indices=indices, extension_names=names)


# ---------------------------------------------------------------------------
# Stage-level GPU toggle resolution
# ---------------------------------------------------------------------------


DEFAULT_GPU_STAGES: frozenset[str] = frozenset(
    {
        "detection",
        "psf",
        "photometry",
        "systematic",
        "advanced",
        "enhancements",
        "faint",
    }
)


def resolve_stage_toggles(
    explicit: dict[str, bool] | None = None,
    disable_all: bool = False,
) -> dict[str, bool]:
    """Resolves the per-stage GPU toggle dictionary.

    ``explicit`` overrides defaults; ``disable_all`` returns an all-
    False dictionary that forces CPU execution everywhere.
    """
    if disable_all:
        return {stage: False for stage in DEFAULT_GPU_STAGES}
    toggles = {stage: True for stage in DEFAULT_GPU_STAGES}
    if explicit:
        for k, v in explicit.items():
            toggles[k] = bool(v)
    return toggles
