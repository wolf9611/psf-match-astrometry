# GPU memory probing
# ---------------------------------------------------------------------------


def free_gpu_bytes() -> int | None:
    """Returns free GPU memory in bytes, or None when no GPU is available."""
    try:
        import cupy  # type: ignore

        mem = cupy.cuda.runtime.memGetInfo()
        # memGetInfo returns (free, total) in bytes
        return int(mem[0])
    except Exception:
        pass
    try:
        import torch  # type: ignore

        if torch.cuda.is_available():
            return int(torch.cuda.mem_get_info()[0])
    except Exception:
        pass
    return None


