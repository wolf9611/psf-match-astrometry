"""
Memory-aware batching utilities for the GPU layer.

Provides ``BatchSizer`` for choosing safe batch sizes based on
available GPU memory, and ``iter_batches`` for chunked iteration over
catalog rows or stamp arrays.  Also provides ``MEFPlan`` for
orchestrating batched processing of multi-extension FITS files.
"""

from __future__ import annotations

from collections.abc import Iterator
from dataclasses import dataclass

from src.logger import get_logger

logger = get_logger("gpu.batching")


@dataclass
class BatchSizer:
    """Computes a safe batch size for GPU operations.

    ``element_bytes`` is the per-element memory footprint (e.g. 8 for
    float64), ``budget_fraction`` is the fraction of free GPU memory
    the batch is allowed to consume (default 25%).
    """

    element_bytes: int = 8
    budget_fraction: float = 0.25
    min_batch: int = 32
    max_batch: int = 65536
    fallback_batch: int = 1024

    def safe_batch(
        self, n_elements_per_item: int, free_bytes: int | None = None
    ) -> int:
        """Returns the safe batch size given per-item element count.

        When ``free_bytes`` is None (no GPU probe available), returns
        ``self.fallback_batch``.
        """
        if free_bytes is None or free_bytes <= 0:
            return self.fallback_batch
        per_item_bytes = n_elements_per_item * self.element_bytes
        # Allow ``budget_fraction`` of free memory; round down.
        budget = int(free_bytes * self.budget_fraction)
        b = max(self.min_batch, budget // max(per_item_bytes, 1))
        return min(self.max_batch, b)


def iter_batches(
    n: int, batch_size: int, drop_last: bool = False
) -> Iterator[tuple[int, int]]:
    """Yields ``(start, end)`` index pairs covering ``[0, n)``.

    When ``drop_last=True`` the final partial batch is skipped.
    """
    if batch_size <= 0:
        raise ValueError("iter_batches: batch_size must be positive")
    for start in range(0, n, batch_size):
        end = min(start + batch_size, n)
        if drop_last and end - start < batch_size:
            return
        yield start, end


